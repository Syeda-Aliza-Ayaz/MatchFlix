-------- 2.6  USER_RATINGS
-------- Core of the rating engine. All 8 dimensions enforced with CHECK constraints.
-------- -----------------------------------------------------------------------------
------
------CREATE TABLE user_ratings (
------    rating_id           NUMBER          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
------    user_id             NUMBER          NOT NULL,
------    movie_id            NUMBER          NOT NULL,
------
------    -- 8 psychological dimensions — all enforced 1.00–10.00
------    emotional_impact    NUMBER(4,2)     NOT NULL CHECK (emotional_impact    BETWEEN 1.00 AND 10.00),
------    cinematography      NUMBER(4,2)     NOT NULL CHECK (cinematography      BETWEEN 1.00 AND 10.00),
------    audio_design        NUMBER(4,2)     NOT NULL CHECK (audio_design        BETWEEN 1.00 AND 10.00),
------    narrative_coherence NUMBER(4,2)     NOT NULL CHECK (narrative_coherence BETWEEN 1.00 AND 10.00),
------    moral_conflict      NUMBER(4,2)     NOT NULL CHECK (moral_conflict      BETWEEN 1.00 AND 10.00),
------    thematic_depth      NUMBER(4,2)     NOT NULL CHECK (thematic_depth      BETWEEN 1.00 AND 10.00),
------    pacing              NUMBER(4,2)     NOT NULL CHECK (pacing              BETWEEN 1.00 AND 10.00),
------    rewatch_value       NUMBER(4,2)     NOT NULL CHECK (rewatch_value       BETWEEN 1.00 AND 10.00),
------
------    overall_score       NUMBER(4,2)     CHECK (overall_score BETWEEN 1.00 AND 10.00),
------    review_text         CLOB,
------    watched_at          DATE,
------    created_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------    updated_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------
------    CONSTRAINT fk_ur_user           FOREIGN KEY (user_id)   REFERENCES users(user_id)   ON DELETE CASCADE,
------    CONSTRAINT fk_ur_movie          FOREIGN KEY (movie_id)  REFERENCES movies(movie_id),
------    CONSTRAINT uq_ur_user_movie     UNIQUE (user_id, movie_id)
------);
------
------COMMENT ON TABLE  user_ratings                  IS 'Core rating engine — one row per user per movie';
------COMMENT ON COLUMN user_ratings.overall_score    IS 'Optional — separate from the 8 dimension scores';
