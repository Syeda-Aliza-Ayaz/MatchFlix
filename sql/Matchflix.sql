-------- -----------------------------------------------------------------------------
-------- 2.7  COMPATIBILITY_CACHE
-------- Precomputed compatibility between two users.
-------- user_a_id < user_b_id enforced via CHECK constraint (chk_cc_user_order).
-------- JSON → CLOB with IS JSON constraint (Oracle 12c+).
-------- -----------------------------------------------------------------------------
------
------CREATE TABLE compatibility_cache (
------    cache_id            NUMBER          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
------    user_a_id           NUMBER          NOT NULL,
------    user_b_id           NUMBER          NOT NULL,
------
------    -- Overall and per-dimension alignment scores (0.0000 – 1.0000)
------    overall_score       NUMBER(5,4)     NOT NULL CHECK (overall_score       BETWEEN 0 AND 1),
------    emotional_align     NUMBER(5,4)     NOT NULL CHECK (emotional_align     BETWEEN 0 AND 1),
------    cinematography_align NUMBER(5,4)   NOT NULL CHECK (cinematography_align BETWEEN 0 AND 1),
------    audio_align         NUMBER(5,4)     NOT NULL CHECK (audio_align         BETWEEN 0 AND 1),
------    narrative_align     NUMBER(5,4)     NOT NULL CHECK (narrative_align     BETWEEN 0 AND 1),
------    moral_align         NUMBER(5,4)     NOT NULL CHECK (moral_align         BETWEEN 0 AND 1),
------    thematic_align      NUMBER(5,4)     NOT NULL CHECK (thematic_align      BETWEEN 0 AND 1),
------    pacing_align        NUMBER(5,4)     NOT NULL CHECK (pacing_align        BETWEEN 0 AND 1),
------    rewatch_align       NUMBER(5,4)     NOT NULL CHECK (rewatch_align       BETWEEN 0 AND 1),
------
------    most_aligned_dim    VARCHAR2(30)    CHECK (most_aligned_dim IN (
------                                            'emotional_impact','cinematography','audio_design',
------                                            'narrative_coherence','moral_conflict','thematic_depth',
------                                            'pacing','rewatch_value'
------                                        )),
------    least_aligned_dim   VARCHAR2(30)    CHECK (least_aligned_dim IN (
------                                            'emotional_impact','cinematography','audio_design',
------                                            'narrative_coherence','moral_conflict','thematic_depth',
------                                            'pacing','rewatch_value'
------                                        )),
------    shared_movie_count  NUMBER(5,0)     DEFAULT 0 NOT NULL,
------    is_stale            NUMBER(1,0)     DEFAULT 0 NOT NULL CHECK (is_stale IN (0,1)),
------    archetype           VARCHAR2(60),
------    conflict_triggers   CLOB            CHECK (conflict_triggers IS JSON),
------    created_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------    calculated_at       TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------
------    CONSTRAINT fk_cc_user_a         FOREIGN KEY (user_a_id) REFERENCES users(user_id) ON DELETE CASCADE,
------    CONSTRAINT fk_cc_user_b         FOREIGN KEY (user_b_id) REFERENCES users(user_id) ON DELETE CASCADE,
------    CONSTRAINT uq_cc_pair           UNIQUE (user_a_id, user_b_id),
------    CONSTRAINT chk_cc_user_order    CHECK (user_a_id < user_b_id)
------);
------
------COMMENT ON COLUMN compatibility_cache.conflict_triggers IS 'JSON array of dimension keys where gap > 6, e.g. ["moral_conflict","pacing"]';
------COMMENT ON COLUMN compatibility_cache.created_at        IS 'First creation — distinct from calculated_at which updates on recalc';
------COMMENT ON COLUMN compatibility_cache.is_stale          IS '1 = needs background recalculation';
------
