-------- -----------------------------------------------------------------------------
-------- 2.11  SOLO_SESSIONS
-------- Tracks a single user smart finder session.
-------- filter_weights = Q&A-derived dimension weights (JSON)
-------- dimension_filters = slider-based threshold filters (JSON)
-------- Discovery-first: no year/runtime/language filters.
-------- -----------------------------------------------------------------------------
------
------CREATE TABLE solo_sessions (
------    session_id          NUMBER          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
------    user_id             NUMBER          NOT NULL,
------    filter_weights      CLOB            NOT NULL CHECK (filter_weights IS JSON),
------    dimension_filters   CLOB            CHECK (dimension_filters IS JSON),
------    genre_filter        CLOB            CHECK (genre_filter IS JSON),
------    mood_tag            VARCHAR2(60),
------    status              VARCHAR2(10)    DEFAULT 'ACTIVE' NOT NULL CHECK (status IN (
------                                            'ACTIVE','COMPLETED','EXPIRED'
------                                        )),
------    created_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------    completed_at        TIMESTAMP,
------
------    CONSTRAINT fk_ss_user           FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
------);
------
------COMMENT ON COLUMN solo_sessions.filter_weights    IS 'QnA-derived weights e.g. {"pacing": 1.5, "thematic_depth": 1.2}';
------COMMENT ON COLUMN solo_sessions.dimension_filters IS 'Slider thresholds e.g. {"pacing": {"min": 7}, "thematic_depth": {"min": 6, "max": 9}}';
------COMMENT ON COLUMN solo_sessions.genre_filter      IS 'JSON array of genre_id values e.g. [1, 4, 7]';
------
------
