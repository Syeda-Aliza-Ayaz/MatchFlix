-------- 2.1  USERS
-------- Central user entity. MBTI enforced via CHECK with all 16 valid types.
-------- BOOLEAN → NUMBER(1,0) CHECK (0 or 1) in Oracle
-------- DATETIME → TIMESTAMP in Oracle
-------- -----------------------------------------------------------------------------
------
------CREATE TABLE users (
------    user_id         NUMBER          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
------    username        VARCHAR2(50)    NOT NULL,
------    email           VARCHAR2(120)   NOT NULL,
------    password_hash   VARCHAR2(255)   NOT NULL,
------    display_name    VARCHAR2(80),
------    age             NUMBER(3,0)     CHECK (age BETWEEN 0 AND 150),
------    mbti_type       VARCHAR2(4)     CHECK (mbti_type IN (
------                                        'INTJ','INTP','ENTJ','ENTP',
------                                        'INFJ','INFP','ENFJ','ENFP',
------                                        'ISTJ','ISFJ','ESTJ','ESFJ',
------                                        'ISTP','ISFP','ESTP','ESFP'
------                                    )),
------    avatar_url      VARCHAR2(500),
------    is_deleted      NUMBER(1,0)     DEFAULT 0 NOT NULL CHECK (is_deleted IN (0,1)),
------    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------    updated_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------
------    CONSTRAINT uq_users_username    UNIQUE (username),
------    CONSTRAINT uq_users_email       UNIQUE (email)
------);
------
------COMMENT ON TABLE  users               IS 'Central user entity';
------COMMENT ON COLUMN users.mbti_type     IS 'DB-enforced ENUM of all 16 MBTI types';
------COMMENT ON COLUMN users.is_deleted    IS 'Soft delete flag — never hard delete';
------COMMENT ON COLUMN users.updated_at    IS 'Update via trigger — see SECTION 5';
------
