-------- -----------------------------------------------------------------------------
-------- 2.2  USER_DIMENSION_WEIGHTS
-------- One row per user per dimension (8 rows per user on signup).
-------- Replaces the JSON dimension_weights column from v1.
-------- dimension enforced via CHECK — Oracle has no ENUM type.
-------- -----------------------------------------------------------------------------
------
------CREATE TABLE user_dimension_weights (
------    weight_id   NUMBER          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
------    user_id     NUMBER          NOT NULL,
------    dimension   VARCHAR2(30)    NOT NULL CHECK (dimension IN (
------                                    'emotional_impact','cinematography','audio_design',
------                                    'narrative_coherence','moral_conflict','thematic_depth',
------                                    'pacing','rewatch_value'
------                                )),
------    weight      NUMBER(4,2)     DEFAULT 1.00 NOT NULL CHECK (weight > 0),
------    updated_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
------
------    CONSTRAINT fk_udw_user      FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
------    CONSTRAINT uq_udw_user_dim  UNIQUE (user_id, dimension)
------);
------
------COMMENT ON TABLE  user_dimension_weights            IS 'Per-user weights for each of the 8 rating dimensions';
------COMMENT ON COLUMN user_dimension_weights.dimension  IS 'One of 8 fixed dimension keys';
------
